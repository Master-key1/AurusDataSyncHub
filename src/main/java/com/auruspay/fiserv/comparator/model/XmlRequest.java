package com.auruspay.comparator.model;

public class XmlRequest {
	
	private String approvedXmlRequest;
	private String declinedXmlRequest;
	
	public String getApprovedXmlRequest() {
		return approvedXmlRequest;
	}
	public void setApprovedXmlRequest(String approvedXmlRequest) {
		this.approvedXmlRequest = approvedXmlRequest;
	}
	public String getDeclinedXmlRequest() {
		return declinedXmlRequest;
	}
	public void setDeclinedXmlRequest(String declinedXmlRequest) {
		this.declinedXmlRequest = declinedXmlRequest;
	}
	
	
	

}
